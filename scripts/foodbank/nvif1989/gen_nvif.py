"""Build src/lib/nvif/data.ts from the hand-transcribed tables of
"Nutritive Value of Indian Foods" (C. Gopalan, B.V. Rama Sastri, S.C. Balasubramanian;
revised by B.S. Narasinga Rao, Y.G. Deosthale, K.C. Pant; NIN-ICMR, 1989 ed., 1993 reprint).

Source files in this folder (transcribed from page images of the scanned book; values exactly
as printed, including the book's own obvious misprints, which docs/nutrient-sources.md lists):
  table1_proximate.psv  Table 1  Proximate principles, common foods (#1-451)
  table2_vitamins.psv   Table 2  Vitamin content, common foods
  table3_minerals.txt   Table 3  Minerals & trace elements, common foods
                        (columns: sl variant Mg Na K Cu Mn Mo Zn Cr S Cl; "*" = main row, "-" = not given)
  mapping.py            food-bank ingredient key -> book serial number

Run:  python3 scripts/foodbank/nvif1989/gen_nvif.py
"""
import csv
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, HERE)
from mapping import APPROX, MAP  # noqa: E402

num = lambda v: float(v) if v.strip() else None

t1 = list(csv.DictReader(open(os.path.join(HERE, "table1_proximate.psv")), delimiter="|"))
t2 = {int(r["sl"]): r for r in csv.DictReader(open(os.path.join(HERE, "table2_vitamins.psv")), delimiter="|")}
MIN_COLS = ["magnesium", "sodium", "potassium", "copper", "manganese", "molybdenum", "zinc", "chromium", "sulphur", "chlorine"]
t3, t3var = {}, {}
for line in open(os.path.join(HERE, "table3_minerals.txt")):
    p = line.split()
    if not p:
        continue
    sl, var = int(p[0]), p[1]
    rec = {k: (None if x == "-" else float(x)) for k, x in zip(MIN_COLS, p[2:])}
    rec = {k: v for k, v in rec.items() if v is not None}
    if var == "*":
        t3[sl] = rec
    else:
        t3var.setdefault(sl, {})[var] = rec

foods = []
for r in t1:
    sl = int(r["sl"])
    f = {"sl": sl, "name": r["name"], "group": r["group"]}
    for k in ["moisture", "protein", "fat", "minerals", "fibre", "carbs", "kcal", "calcium", "phosphorus", "iron"]:
        f[k] = num(r[k])
    v = t2.get(sl)
    if v:
        for k in ["carotene", "thiamine", "riboflavin", "niacin", "b6", "folate_free", "folate_total", "vitc", "choline"]:
            f[k] = num(v[k])
    m = t3.get(sl) or (next(iter(t3var[sl].values())) if sl in t3var else None)
    if m:
        f.update(m)
    if sl in t3var:
        f["mineralVariants"] = t3var[sl]
    foods.append({k: v for k, v in f.items() if v is not None})

assert [f["sl"] for f in foods] == list(range(1, 452)), "serials must run 1..451"
assert all(sl in {f["sl"] for f in foods} for sl in MAP.values())

ingredient_map = {k: {"sl": sl, **({"approx": True} if k in APPROX else {})} for k, sl in sorted(MAP.items())}

ts = f'''// AUTO-GENERATED by scripts/foodbank/nvif1989/gen_nvif.py — do not hand-edit.
//
// "Nutritive Value of Indian Foods" — C. Gopalan, B.V. Rama Sastri, S.C. Balasubramanian;
// revised & updated by B.S. Narasinga Rao, Y.G. Deosthale, K.C. Pant. National Institute of
// Nutrition (ICMR), Hyderabad. 1989 edition, 1993 reprint. Common foods, Tables 1–3.
//
// REFERENCE ONLY. The food bank computes nutrition from IFCT 2017 (NIN's newer tables). Note the
// method differences when comparing: this book's "carbs" are by difference (they include most
// dietary fibre), "fibre" is crude fibre (well below dietary fibre), and energy is 4/4/9 kcal/g.
// All values per 100 g edible portion. Missing = not given in the book (not zero).

export interface NvifFood {{
  sl: number;
  name: string;
  group: string;
  moisture?: number; protein?: number; fat?: number; minerals?: number;
  /** crude fibre, g */
  fibre?: number;
  /** carbohydrate by difference, g */
  carbs?: number;
  kcal?: number; calcium?: number; phosphorus?: number; iron?: number;
  /** µg */ carotene?: number;
  thiamine?: number; riboflavin?: number; niacin?: number; b6?: number;
  /** µg */ folate_free?: number;
  /** µg */ folate_total?: number;
  /** mg */ vitc?: number;
  choline?: number;
  magnesium?: number; sodium?: number; potassium?: number; copper?: number; manganese?: number;
  molybdenum?: number; zinc?: number; chromium?: number; sulphur?: number; chlorine?: number;
  /** extra mineral rows the book gives for varieties (e.g. dhal vs whole) */
  mineralVariants?: Record<string, Record<string, number>>;
}}

export const NVIF_FOODS: NvifFood[] = {json.dumps(foods, indent=0, ensure_ascii=False)};

/** Food-bank ingredient key → matching food in the book. approx = related form/variety, not identical. */
export const INGREDIENT_TO_NVIF: Record<string, {{ sl: number; approx?: boolean }}> = {json.dumps(ingredient_map, indent=0)};
'''
out = os.path.join(ROOT, "src", "lib", "nvif", "data.ts")
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w", encoding="utf-8").write(ts)
print(f"wrote {len(foods)} foods, {len(ingredient_map)} ingredient links -> {out}")
