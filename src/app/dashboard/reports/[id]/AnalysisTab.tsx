"use client";

import { useState } from "react";
import Link from "next/link";
import { Analysis } from "@/lib/types";
import type { LoadedReport } from "./ReportWorkspace";

function EditableList({
  title,
  items,
  onChange,
  tone = "neutral",
}: {
  title: string;
  items: string[];
  onChange: (items: string[]) => void;
  tone?: "good" | "bad" | "neutral";
}) {
  const [draft, setDraft] = useState("");
  const dot =
    tone === "good"
      ? "text-brand-600"
      : tone === "bad"
        ? "text-red-500"
        : "text-slate-400";

  return (
    <div className="card p-5">
      <h3 className="mb-3 text-sm font-bold uppercase tracking-wide text-brand-700">
        {title}
      </h3>
      <ul className="space-y-2">
        {items.map((item, i) => (
          <li key={i} className="flex items-start gap-2">
            <span className={`mt-1 ${dot}`}>
              {tone === "bad" ? "✕" : "•"}
            </span>
            <input
              className="flex-1 rounded border border-transparent px-1 py-0.5 text-sm hover:border-slate-200 focus:border-brand-400 focus:outline-none"
              value={item}
              onChange={(e) => {
                const next = [...items];
                next[i] = e.target.value;
                onChange(next);
              }}
            />
            <button
              className="text-xs text-slate-300 hover:text-red-500"
              onClick={() => onChange(items.filter((_, j) => j !== i))}
              title="Remove"
            >
              ✕
            </button>
          </li>
        ))}
      </ul>
      <div className="mt-3 flex gap-2">
        <input
          className="input text-sm"
          placeholder="Add item…"
          value={draft}
          onChange={(e) => setDraft(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === "Enter" && draft.trim()) {
              onChange([...items, draft.trim()]);
              setDraft("");
            }
          }}
        />
        <button
          className="btn-secondary text-xs"
          onClick={() => {
            if (draft.trim()) {
              onChange([...items, draft.trim()]);
              setDraft("");
            }
          }}
        >
          Add
        </button>
      </div>
    </div>
  );
}

export default function AnalysisTab({
  report,
  hasApiKey,
  onAnalysisChange,
  onSave,
  saving,
}: {
  report: LoadedReport;
  hasApiKey: boolean;
  onAnalysisChange: (a: Analysis) => void;
  onSave: (a: Analysis) => void;
  saving: boolean;
}) {
  const a = report.analysis;
  const [aiBusy, setAiBusy] = useState(false);
  const [aiError, setAiError] = useState<string | null>(null);

  const patch = (p: Partial<Analysis>) => onAnalysisChange({ ...a, ...p });

  async function runAI() {
    setAiBusy(true);
    setAiError(null);
    try {
      const res = await fetch(`/api/reports/${report.id}/ai`, { method: "POST" });
      const data = await res.json();
      if (!res.ok) {
        setAiError(data.error ?? "AI analysis failed.");
        return;
      }
      onAnalysisChange(data.analysis);
    } catch {
      setAiError("Network error running AI analysis.");
    } finally {
      setAiBusy(false);
    }
  }

  return (
    <div className="space-y-6">
      {/* AI bar */}
      <div className="card flex flex-wrap items-center justify-between gap-3 p-4">
        <div>
          <div className="text-sm font-semibold text-slate-800">
            Analysis generated by{" "}
            <span className="capitalize text-brand-700">
              {a.generatedBy === "claude" ? "Claude AI" : "Built-in engine"}
            </span>
          </div>
          <p className="text-xs text-slate-500">
            {hasApiKey
              ? "Enhance the built-in analysis with a personalised Claude narrative."
              : "Add an Anthropic API key in Settings to enable Claude-enhanced analysis."}
          </p>
        </div>
        <div className="flex items-center gap-2">
          {hasApiKey ? (
            <button className="btn-primary text-sm" disabled={aiBusy} onClick={runAI}>
              {aiBusy ? "Analysing…" : "✨ Enhance with AI"}
            </button>
          ) : (
            <Link href="/dashboard/settings" className="btn-secondary text-sm">
              Configure API key
            </Link>
          )}
        </div>
      </div>
      {aiError && (
        <div className="rounded-lg bg-red-50 px-4 py-2 text-sm text-red-700">
          {aiError}
        </div>
      )}

      {a.aiNarrative && (
        <div className="card border-l-4 border-brand-500 p-5">
          <h3 className="mb-2 text-sm font-bold uppercase tracking-wide text-brand-700">
            Clinical Narrative
          </h3>
          <p className="whitespace-pre-line text-sm leading-relaxed text-slate-700">
            {a.aiNarrative}
          </p>
        </div>
      )}

      <EditableList
        title="Dietary Goals"
        items={a.dietaryGoals}
        onChange={(v) => patch({ dietaryGoals: v })}
        tone="good"
      />

      <div className="grid grid-cols-1 gap-6 lg:grid-cols-2">
        <EditableList title="Do's" items={a.dos} onChange={(v) => patch({ dos: v })} tone="good" />
        <EditableList title="Don'ts" items={a.donts} onChange={(v) => patch({ donts: v })} tone="bad" />
        <EditableList
          title="Foods to Include"
          items={a.foodsToInclude}
          onChange={(v) => patch({ foodsToInclude: v })}
          tone="good"
        />
        <EditableList
          title="Foods to Exclude"
          items={a.foodsToExclude}
          onChange={(v) => patch({ foodsToExclude: v })}
          tone="bad"
        />
      </div>

      <div className="flex justify-end">
        <button className="btn-primary" disabled={saving} onClick={() => onSave(a)}>
          {saving ? "Saving…" : "Save analysis"}
        </button>
      </div>
    </div>
  );
}
